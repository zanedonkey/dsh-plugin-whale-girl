export const INTERACTION_KEYS = Object.freeze(Object.fromEntries(['headpat', 'eating'].map(kind =>
  [kind, Object.freeze(Object.keys(MESSAGES.en).filter(key => key.startsWith(`interaction.${kind}.`)))])));

/** Pick once per interaction, avoiding the previous line without rerolling on paint. */
export function chooseInteractionKey(kind, previous, random = Math.random) {
  const choices = (INTERACTION_KEYS[kind] || []).filter(key => key !== previous);
  if (!choices.length) return undefined;
  const draw = Math.max(0, Math.min(1, Number(random()) || 0));
  return choices[Math.min(choices.length - 1, Math.floor(draw * choices.length))];
}

export function normalizeLanguage(language) {
  return typeof language === 'string' && /^zh(?:$|[-_])/i.test(language.trim()) ? 'zh' : 'en';
}
export function translate(language, key, values = {}) {
  const message = MESSAGES[normalizeLanguage(language)][key] ?? MESSAGES.en[key] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
